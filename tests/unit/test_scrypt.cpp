#include "test_helpers.h"

#include <cstring>

TEST(Scrypt, Rfc7914) {
  static const unsigned char empty[64] = {
    0x77, 0xd6, 0x57, 0x62, 0x38, 0x65, 0x7b, 0x20,
    0x3b, 0x19, 0xca, 0x42, 0xc1, 0x8a, 0x04, 0x97,
    0xf1, 0x6b, 0x48, 0x44, 0xe3, 0x07, 0x4a, 0xe8,
    0xdf, 0xdf, 0xfa, 0x3f, 0xed, 0xe2, 0x14, 0x42,
    0xfc, 0xd0, 0x06, 0x9d, 0xed, 0x09, 0x48, 0xf8,
    0x32, 0x6a, 0x75, 0x3a, 0x0f, 0xc8, 0x1f, 0x17,
    0xe8, 0xd3, 0xe0, 0xfb, 0x2e, 0x0d, 0x36, 0x28,
    0xcf, 0x35, 0xe2, 0x0c, 0x38, 0xd1, 0x89, 0x06
  };
  static const unsigned char password[] = {
    0x70, 0x61, 0x73, 0x73, 0x77, 0x6f, 0x72, 0x64
  };
  static const unsigned char salt[] = {0x4e, 0x61, 0x43, 0x6c};
  static const unsigned char nacl[64] = {
    0xfd, 0xba, 0xbe, 0x1c, 0x9d, 0x34, 0x72, 0x00,
    0x78, 0x56, 0xe7, 0x19, 0x0d, 0x01, 0xe9, 0xfe,
    0x7c, 0x6a, 0xd7, 0xcb, 0xc8, 0x23, 0x78, 0x30,
    0xe7, 0x73, 0x76, 0x63, 0x4b, 0x37, 0x31, 0x62,
    0x2e, 0xaf, 0x30, 0xd9, 0x2e, 0x22, 0xa3, 0x88,
    0x6f, 0xf1, 0x09, 0x27, 0x9d, 0x98, 0x30, 0xda,
    0xc7, 0x27, 0xaf, 0xb9, 0x4a, 0x83, 0xee, 0x6d,
    0x83, 0x60, 0xcb, 0xdf, 0xa2, 0xcc, 0x06, 0x40
  };
  unsigned char dk[64];

  ASSERT_EQ(gsec_scrypt(nullptr, 0, nullptr, 0, 16, 1, 1, dk, sizeof dk),
      GSEC_OK);
  EXPECT_EQ(gsec_equal(dk, empty, sizeof dk), GSEC_OK);
  ASSERT_EQ(gsec_scrypt(password, sizeof password, salt, sizeof salt, 1024, 8,
      16, dk, sizeof dk), GSEC_OK);
  EXPECT_EQ(gsec_equal(dk, nacl, sizeof dk), GSEC_OK);
}

TEST(Scrypt, RejectsABadCall) {
  unsigned char dk[4];
  unsigned char password[1] = {1};

  dk[0] = 0xa5;
  EXPECT_EQ(gsec_scrypt(password, 1, password, 1, 3, 1, 1, dk, 4),
      GSEC_ERR_INVALID);
  EXPECT_EQ(dk[0], 0xa5);
  EXPECT_EQ(gsec_scrypt(password, 1, password, 1, 2, 0, 1, dk, 4),
      GSEC_ERR_INVALID);
  EXPECT_EQ(gsec_scrypt(nullptr, 1, nullptr, 0, 2, 1, 1, dk, 4),
      GSEC_ERR_INVALID);
  EXPECT_EQ(gsec_scrypt(nullptr, 0, nullptr, 0, 16, 1, 1, nullptr, 0), GSEC_OK);
}

int main(int argc, char ** argv) {
  ::testing::InitGoogleTest(&argc, argv);
  return RUN_ALL_TESTS();
}
